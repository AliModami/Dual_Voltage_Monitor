/**
 * @brief
 *   حرکت دادن نمایش به سمت چپ
 *
 * @details
 *   این دستور محتویات DDRAM را Shift می‌دهد.
 *
 *   اطلاعات پاک نمی‌شود.
 *
 */
void LCD_ScrollLeft(void)
{
    /*
     * دستور:
     *
     * Shift Display Left
     *
     */
    LCD_SendCommand(0x18);
}





/**
 * @brief
 *   حرکت دادن نمایش به سمت راست
 *
 */
void LCD_ScrollRight(void)
{
    /*
     * دستور:
     *
     * Shift Display Right
     *
     */
    LCD_SendCommand(0x1C);
}





