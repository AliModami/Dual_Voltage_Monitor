 /*
  * ---------------------------------------------------------------------------
  * ARRAY_SIZE()
  * ---------------------------------------------------------------------------
  *
  * این ماکرو تعداد عناصر موجود در یک آرایه ثابت
  * را محاسبه می‌کند.
  *
  * مزایا:
  *
  *      • حذف اعداد ثابت از برنامه
  *
  *      • جلوگیری از خطا هنگام تغییر اندازه آرایه
  *
  *      • افزایش خوانایی کد
  *
  *
  * مثال:
  *
  *      uint8_t Data[10];
  *
  *      ARRAY_SIZE(Data)
  *
  *              نتیجه:
  *
  *                  10
  *
  */

 #define ARRAY_SIZE(x) \
     (sizeof(x) / sizeof((x)[0]))




 /*
  * ---------------------------------------------------------------------------
  * UNUSED()
  * ---------------------------------------------------------------------------
  *
  * در بسیاری از Callback ها یا Prototype ها
  * ممکن است پارامتری وجود داشته باشد که
  * فعلاً از آن استفاده نشود.
  *
  * Compiler برای چنین پارامترهایی Warning تولید می‌کند.
  *
  * این ماکرو به صورت رسمی اعلام می‌کند
  * که این پارامتر عمداً استفاده نشده است.
  *
  *
  * مثال:
  *
  *      void Function(uint8_t value)
  *      {
  *          UNUSED(value);
  *      }
  *
  */

 #define UNUSED(x) \
     ((void)(x))




