/******************************************************************************
 *
 * Menu Callback Type
 *
 ******************************************************************************

تمام Action های سیستم از یک Prototype مشترک استفاده می‌کنند.

این طراحی باعث می‌شود Engine هیچ اطلاعی از نوع Action
نداشته باشد و فقط Callback را فراخوانی کند.

******************************************************************************/

/*
 * Forward Declaration
 *
 * به دلیل اینکه MenuItem_t هنوز تعریف نشده است،
 * فقط نام آن را به کامپایلر معرفی می‌کنیم.
 */

typedef struct MenuItem MenuItem_t;


/*
 * Callback Prototype
 */

typedef void (*MenuCallback_t)(MenuItem_t *item);



/******************************************************************************
 *
 * Menu Item Object
 *
 ******************************************************************************

MenuItem کوچک‌ترین واحد Database است.

هر MenuItem دقیقاً متعلق به یک Page است.

ممکن است:

    • یک Action اجرا کند.

    • وارد یک SubMenu شود.

    • یک مقدار را نمایش دهد.

    • یک مقدار را ویرایش کند.

******************************************************************************/

struct MenuItem
{

    /**********************************************************************
     * Item Identity
     **********************************************************************/

    MenuItemId_t id;

    const char *title;

    MenuItemType_t type;



    /**********************************************************************
     * Navigation
     **********************************************************************/

    MenuPage_t *ownerPage;

    MenuPage_t *childPage;

    MenuItem_t *next;

    MenuItem_t *previous;



    /**********************************************************************
     * Action Callback
     **********************************************************************/

    MenuCallback_t enterCallback;

};

/******************************************************************************
 *
 * Menu Page Object
 *
 ******************************************************************************

هر MenuPage مالک مجموعه‌ای از MenuItem ها است.

Engine همیشه فقط با یک Page فعال کار می‌کند.

هر Page شامل یک Linked List دوبل از MenuItem ها است.

            +-----------------------------+
            |        MenuPage             |
            +-----------------------------+
            | Title                       |
            | First Item --------------------+
            | Last Item -------------+      |
            | Selected Item ------+  |      |
            +----------------------+ |      |
                                     |      |
                                     v      v

            Item1 <----> Item2 <----> Item3 <----> Item4


******************************************************************************/

struct MenuPage
{

    /**********************************************************************
     *
     * Page Identity
     *
     **********************************************************************/

    MenuPageId_t id;


    /*
     * Page Title
     */

    const char *title;



    /**********************************************************************
     *
     * Linked List
     *
     **********************************************************************/

    /*
     * First item of this page.
     */

    MenuItem_t *firstItem;


    /*
     * Last item of this page.
     */

    MenuItem_t *lastItem;


    /*
     * Currently selected item.
     */

    MenuItem_t *selectedItem;



    /**********************************************************************
     *
     * Navigation
     *
     **********************************************************************/

    /*
     * Parent Page
     *
     * Root page has NULL.
     */

    MenuPage_t *parentPage;



    /**********************************************************************
     *
     * Statistics
     *
     **********************************************************************/

    /*
     * Number of items in this page.
     */

    uint8_t itemCount;

};
/******************************************************************************
 *
 * Menu Engine Object
 *
 ******************************************************************************

MenuEngine هسته‌ی سیستم Menu است.

این ساختار فقط وضعیت جاری (Runtime State) را نگهداری می‌کند.

نکته مهم:

    MenuEngine مالک هیچ MenuItem یا MenuPage نیست.

تمام Page ها و Item ها در Database
(فایل menu_items.c) به صورت Static ایجاد می‌شوند.

Engine فقط Pointer آن‌ها را نگهداری می‌کند.

******************************************************************************/

struct MenuEngine
{

    /**********************************************************************
     *
     * Current Navigation State
     *
     **********************************************************************/

    /*
     * صفحه جاری
     */

    MenuPage_t *currentPage;


    /*
     * آیتم انتخاب شده جاری
     */

    MenuItem_t *currentItem;



    /**********************************************************************
     *
     * Engine State
     *
     **********************************************************************/

    /*
     * وضعیت فعلی State Machine
     */

    MenuState_t state;



    /**********************************************************************
     *
     * Status Flags
     *
     **********************************************************************/

    /*
     * درخواست Refresh کامل صفحه
     */

    bool pageChanged;


    /*
     * فقط مکان‌نما (Cursor) تغییر کرده است.
     */

    bool selectionChanged;


    /*
     * ورود به حالت ویرایش
     */

    bool editMode;

};



