/******************************************************************************
 *
 * Design Philosophy
 *
 ******************************************************************************

در معماری جدید سیستم Menu فقط سه موجودیت اصلی دارد.


                +----------------+
                |   MenuPage     |
                +----------------+

                       |
                       | owns
                       v

                +----------------+
                |   MenuItem     |
                +----------------+

                       ^
                       |
                +----------------+
                |  MenuEngine    |
                +----------------+


MenuPage

    مالک مجموعه‌ای از MenuItem ها است.


MenuItem

    یک گزینه قابل نمایش یا اجرا است.


MenuEngine

    وضعیت فعلی سیستم Navigation را مدیریت می‌کند.


هیچ‌کدام مسئولیت دیگری را انجام نمی‌دهد.

******************************************************************************/
/******************************************************************************
 *
 * Menu Item Type
 *
 ******************************************************************************/

/*
 *
 * نوع هر آیتم منو
 *
 * این Enum مشخص می‌کند Menu Engine
 * هنگام انتخاب یک Item چه رفتاری داشته باشد.
 *
 *
 * مثال:
 *
 *      Main Menu
 *
 *      +----------------------+
 *      | Live Monitor         | ---> ACTION
 *      | Stream Settings      | ---> SUBMENU
 *      | Baud Rate            | ---> VALUE
 *      | Firmware Version     | ---> INFO
 *      +----------------------+
 *
 */

typedef enum
{

    /**********************************************************************
     *
     * Normal Item
     *
     * فقط نمایش داده می‌شود.
     *
     **********************************************************************/

    MENU_ITEM_NORMAL = 0,



    /**********************************************************************
     *
     * Sub Menu
     *
     * ورود به یک Page دیگر
     *
     **********************************************************************/

    MENU_ITEM_SUBMENU,



    /**********************************************************************
     *
     * Editable Item
     *
     * ورود به حالت ویرایش
     *
     **********************************************************************/

    MENU_ITEM_EDIT,



    /**********************************************************************
     *
     * Value Item
     *
     * نمایش یا ویرایش یک مقدار
     *
     * مثال:
     *
     *      Baud Rate
     *      Sample Time
     *      Alarm Enable
     *
     **********************************************************************/

    MENU_ITEM_VALUE,



    /**********************************************************************
     *
     * Action Item
     *
     * اجرای یک عملیات
     *
     * مثال:
     *
     *      Start Stream
     *      Live Monitor
     *      Factory Reset
     *
     **********************************************************************/

    MENU_ITEM_ACTION,



    /**********************************************************************
     *
     * Information Item
     *
     * فقط اطلاعات نمایش داده می‌شود.
     *
     **********************************************************************/

    MENU_ITEM_INFO

} MenuItemType_t;



/******************************************************************************
 *
 * Menu State
 *
 ******************************************************************************

Menu Engine به صورت یک State Machine ساده
طراحی شده است.

******************************************************************************/

typedef enum
{

    /*
     * موتور غیرفعال است.
     */

    MENU_STATE_IDLE = 0,



    /*
     * حرکت بین آیتم‌های منو
     */

    MENU_STATE_NAVIGATION,



    /*
     * ویرایش مقدار
     */

    MENU_STATE_EDIT,



    /*
     * اجرای Action
     */

    MENU_STATE_ACTION,



    /*
     * نمایش پیام موقت
     *
     * مانند:
     *
     *      Saved
     *      Error
     *      Completed
     *
     */

    MENU_STATE_MESSAGE

} MenuState_t;
/******************************************************************************
 *
 * Menu Event
 *
 ******************************************************************************

نکته معماری:

Menu Engine هرگز Button Driver را نمی‌شناسد.

Button Driver فقط Event تولید می‌کند و Engine
فقط همین Event ها را دریافت می‌کند.

        BUTTON_UP
             │
             ▼
      MENU_EVENT_UP

        BUTTON_DOWN
             │
             ▼
     MENU_EVENT_DOWN

       BUTTON_ENTER
             │
             ▼
    MENU_EVENT_ENTER

        BUTTON_BACK
             │
             ▼
     MENU_EVENT_BACK

******************************************************************************/

typedef enum
{

    /*
     * No Event
     */

    MENU_EVENT_NONE = 0,



    /*
     * Move Selection Up
     */

    MENU_EVENT_UP,



    /*
     * Move Selection Down
     */

    MENU_EVENT_DOWN,



    /*
     * Execute / Enter
     */

    MENU_EVENT_ENTER,



    /*
     * Return to Parent Page
     */

    MENU_EVENT_BACK

} MenuEvent_t;



